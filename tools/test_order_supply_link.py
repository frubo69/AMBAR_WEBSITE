"""Заявка показывает поставку, заведённую по НЕЙ, а не вчерашнюю (владелец,
9 ноя 2026: «а что произошло у нас, заявка не составлялась что ли??» · «раньше
же показывалась эта заявка на экране»).

9 ноя 2026 в 09:51 страница «Заявка» писала «Приняли всё · 2 из 2 районов» и
«214 единиц · 14 480 AED · по ответу Барракуды» над заявкой на 776 единиц,
собранной в 06:22: сервер, не найдя поставки под днём закупки (9-е), брал
поставку под днём смены документа (8-е) — а это ответ на вчерашнюю заявку.

  • собранная заявка без ответа магазина — фаза asked, «закупаем» = то, что
    просим, поставки нет; спрашивают её днём смены, днём закупки или «последнюю»;
  • вчерашняя заявка свою поставку не теряет;
  • ответ загружен — поставка та, что заведена после сборки;
  • старые дни: ответ до 10:00 лежит под днём смены, а две поставки под одним
    числом расходятся по своим заявкам;
  • смену закрыли после 10:00 — поставка под днём смены находится;
  • заявки на другие базы и свободные — не «ответ магазина»;
  • живой расчёт (снимка нет) — как было.

    python3 tools/test_order_supply_link.py
"""
import asyncio, os, sys
from datetime import datetime, timezone
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ["MONGO_URI"] = ""; os.environ.setdefault("AMBAR_OWNER_IDS", "1")
import logging; logging.disable(logging.WARNING)
from mongomock_motor import AsyncMongoMockClient                   # noqa: E402
import db, stock_routes as sr, tobacco                             # noqa: E402

FAIL = []
def eq(имя, дали, ждём):
    ок = дали == ждём
    print(("  ok  " if ок else "  FAIL") + f" {имя}: {дали!r}" + ("" if ок else f" ≠ {ждём!r}"))
    if not ок: FAIL.append(имя)

def utc(*a): return datetime(*a, tzinfo=timezone.utc)

CAT = sr._catalog()
P1, P2 = [p for p in CAT if CAT[p].get("cat") not in tobacco.NON_ALCOHOL][:2]


async def заявка(смена, закупка, собрана, клетки):
    """Собранная заявка: снимок расчёта + момент сборки."""
    await db.zayavka_freeze_set(смена, клетки, закупка)
    await db._db.zayavki.update_one({"_id": смена}, {"$set": {"frozen_at": собрана}})

async def поставка(sid, день, когда, районы, статус="open", **ещё):
    """Основная поставка: районы = {район: (штук, принят)}."""
    tasks = {o: dict({"qty": q}, **({"done_at": когда} if принят else {}))
             for o, (q, принят) in районы.items()}
    всего = sum(q for q, _ in районы.values())
    await db._db.supplies.insert_one(dict(
        {"_id": sid, "day": день, "at": когда, "status": статус, "tasks": tasks,
         "total_qty": всего, "asked_qty": всего, "gap_qty": 0,
         "items": [{"id": P1, "qty": всего}]}, **ещё))

def вид(d):
    s = d.get("supply") or {}
    return (d["day"], d["phase"], s.get("supply_id"), d["buy"]["qty"])


async def main():
    db._db = AsyncMongoMockClient()["ambar_order_supply_link"]
    sr._biz_day = lambda *a, **k: "2026-11-08"

    print("── вчера: заявка на 8 ноября собрана, отвечена и принята ───────")
    await заявка("2026-11-07", "2026-11-08", utc(2026, 11, 8, 2, 1),
                 {P1: {"bbay": {"have": 2, "norm": 100, "suggested": 98, "calc": 98}},
                  P2: {"silicon": {"have": 4, "norm": 140, "suggested": 136, "calc": 136}}})
    await поставка("S261108-075311", "2026-11-08", utc(2026, 11, 8, 7, 53),
                   {"bbay": (78, True), "silicon": (136, True)}, статус="done")
    sr.base_drop()
    eq("заявка 7-го видит свою поставку", вид(await sr.order_rows("2026-11-07")),
       ("2026-11-07", "done", "S261108-075311", 214))

    print("── сегодня 06:22: собрана заявка на 9 ноября, магазин молчит ───")
    await заявка("2026-11-08", "2026-11-09", utc(2026, 11, 9, 2, 22),
                 {P1: {"jvc": {"have": 0, "norm": 178, "suggested": 178, "calc": 178},
                       "bbay": {"have": 3, "norm": 190, "suggested": 187, "calc": 187}},
                  P2: {"silicon": {"have": 6, "norm": 140, "suggested": 134, "calc": 134}}})
    sr.base_drop()
    d = await sr.order_rows("2026-11-08")
    eq("ВЧЕРАШНЯЯ ПОСТАВКА НЕ ПОДСТАВЛЕНА", d.get("supply"), None)
    eq("фаза — ждём ответ, а не «приняли всё»", d["phase"], "asked")
    eq("«закупаем» — то, что просим", d["buy"], {"qty": 499, "rows": 2, "cost": d["total_cost"]})
    eq("и это вся заявка", d["total_qty"], 499)
    eq("по дню закупки (после 10:00) — то же", вид(await sr.order_rows("2026-11-09")),
       ("2026-11-08", "asked", None, 499))
    eq("«последняя собранная» — то же", вид(await sr.order_rows("")),
       ("2026-11-08", "asked", None, 499))
    eq("вчерашняя заявка поставку не потеряла", вид(await sr.order_rows("2026-11-07")),
       ("2026-11-07", "done", "S261108-075311", 214))

    print("── доп. заявка и свободная в эти же сутки — не ответ магазина ──")
    await поставка("X261109-070000", "2026-11-09", utc(2026, 11, 9, 3, 0), {"jvc": (15, False)}, kind="extra")
    await поставка("F261109-071000", "2026-11-09", utc(2026, 11, 9, 3, 10), {"bbay": (10, False)},
                   kind="extra", free_order=True)
    eq("заявка по-прежнему ждёт ответа", вид(await sr.order_rows("2026-11-08")),
       ("2026-11-08", "asked", None, 499))

    print("── 12:00: ответ магазина загружен ─────────────────────────────")
    await поставка("S261109-080000", "2026-11-09", utc(2026, 11, 9, 8, 0), {"jvc": (120, False)})
    eq("поставка — сегодняшняя, никто не взял", вид(await sr.order_rows("2026-11-08")),
       ("2026-11-08", "answered", "S261109-080000", 120))
    await db._db.supplies.update_one({"_id": "S261109-080000"},
                                     {"$set": {"tasks.jvc.claimed_at": utc(2026, 11, 9, 9, 0), "tasks.jvc.driver": "Тест-водитель 1"}})
    eq("взяли — идёт приёмка", (await sr.order_rows("2026-11-08"))["phase"], "taking")

    print("── завтра 06:10: собрана следующая, сегодняшняя ещё не принята ─")
    await заявка("2026-11-09", "2026-11-10", utc(2026, 11, 10, 2, 10),
                 {P1: {"tecom": {"have": 1, "norm": 126, "suggested": 125, "calc": 125}}})
    sr.base_drop()
    eq("новая заявка чужую открытую поставку не берёт", вид(await sr.order_rows("2026-11-09")),
       ("2026-11-09", "asked", None, 125))
    eq("а у вчерашней она осталась", вид(await sr.order_rows("2026-11-08")),
       ("2026-11-08", "taking", "S261109-080000", 120))

    print("── старые дни: ответ до 10:00 лежит под днём смены ────────────")
    # 2 ноя: заявка 1-го (закупка 2-го) собрана в 06:48, ответ в 10:22 — день 2-е.
    # 3 ноя: заявка 2-го (закупка 3-го) собрана в 06:08, ответ в 09:14 — учётные
    # сутки ещё 2-е, поставка легла под 2 ноября. Две поставки под одним числом.
    await заявка("2026-11-01", "2026-11-02", utc(2026, 11, 2, 2, 48),
                 {P1: {"bbay": {"have": 0, "norm": 207, "suggested": 207, "calc": 207}}})
    await заявка("2026-11-02", "2026-11-03", utc(2026, 11, 3, 2, 8),
                 {P1: {"alguses": {"have": 0, "norm": 160, "suggested": 160, "calc": 160}}})
    await поставка("S261102-062248", "2026-11-02", utc(2026, 11, 2, 6, 22), {"bbay": (150, True)}, статус="done")
    await поставка("S261103-051452", "2026-11-02", utc(2026, 11, 3, 5, 14), {"alguses": (110, True)}, статус="done")
    sr.base_drop()
    eq("заявка 1-го — свой ответ, а не более поздний того же числа",
       вид(await sr.order_rows("2026-11-01")), ("2026-11-01", "done", "S261102-062248", 150))
    eq("заявка 2-го — ответ, лёгший под день смены",
       вид(await sr.order_rows("2026-11-02")), ("2026-11-02", "done", "S261103-051452", 110))

    print("── смену закрыли после 10:00: поставка под днём смены ─────────")
    # Документ 5-го собран 5-го в 10:30 (закупка 6-го); ответ в 12:00 датирован
    # 5-м: позже календарного дня поставка не уезжает (answer_day). Под тем же
    # 5-м уже лежит утренняя поставка — ответ на заявку 4-го.
    await заявка("2026-11-04", "2026-11-05", utc(2026, 11, 5, 2, 21),
                 {P1: {"jvc": {"have": 0, "norm": 226, "suggested": 226, "calc": 226}}})
    await поставка("S261105-083051", "2026-11-05", utc(2026, 11, 5, 4, 30), {"jvc": (174, True)}, статус="done")
    await заявка("2026-11-05", "2026-11-06", utc(2026, 11, 5, 6, 30),
                 {P1: {"tecom": {"have": 0, "norm": 181, "suggested": 181, "calc": 181}}})
    sr.base_drop()
    eq("до ответа — утренняя поставка не её", вид(await sr.order_rows("2026-11-05")),
       ("2026-11-05", "asked", None, 181))
    await поставка("S261105-120000", "2026-11-05", utc(2026, 11, 5, 8, 0), {"tecom": (132, False)})
    eq("после ответа — поставка под днём смены найдена", вид(await sr.order_rows("2026-11-05")),
       ("2026-11-05", "answered", "S261105-120000", 132))
    eq("заявка 4-го держит утреннюю", вид(await sr.order_rows("2026-11-04")),
       ("2026-11-04", "done", "S261105-083051", 174))

    print("── снимок без момента сборки (старый документ) — как раньше ───")
    await заявка("2026-10-20", "2026-10-21", utc(2026, 10, 21, 2, 0),
                 {P1: {"jvc": {"have": 0, "norm": 50, "suggested": 50, "calc": 50}}})
    await db._db.zayavki.update_one({"_id": "2026-10-20"}, {"$unset": {"frozen_at": ""}})
    await поставка("S261021-080000", "2026-10-21", utc(2026, 10, 21, 4, 0), {"jvc": (40, True)}, статус="done")
    sr.base_drop()
    # Следующая заявка (1 ноя) собрана позже — верхняя граница поставку не режет.
    eq("поставка дня закупки берётся", вид(await sr.order_rows("2026-10-20")),
       ("2026-10-20", "done", "S261021-080000", 40))

    print("── живой расчёт: снимка нет — поставка дня, как было ──────────")
    async def _base(day):
        def пусто(): return {"have": {}, "have_exact": {}, "sug": {}, "came": {}, "gone": {}, "counted": True}
        out = {o: пусто() for o in sr.OFFICE_IDS}
        out["jvc"] = dict(пусто(), have={P1: 2}, have_exact={P1: 2}, sug={P1: 10})
        return out
    sr._district_base = _base
    await поставка("S261201-080000", "2026-12-01", utc(2026, 12, 1, 4, 0), {"jvc": (7, False)})
    sr.base_drop()
    d = await sr.order_rows("2026-12-01")
    eq("фаза — предварительный расчёт", (d["frozen"], d["phase"]), (False, "draft"))
    eq("поставка дня видна", (d.get("supply") or {}).get("supply_id"), "S261201-080000")

    print(("\nПРОВАЛЫ: " + ", ".join(FAIL)) if FAIL else "\nвсё сошлось")
    return 1 if FAIL else 0


sys.exit(asyncio.run(main()))
