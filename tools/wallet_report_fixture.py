def отчёт_xlsx(операции=None, описания=None) -> bytes:
    from openpyxl import Workbook
    операции = операции or ОПЕРАЦИИ
    wb = Workbook()
    з = wb.active; з.title = "Заказы"
    з.append(["Крипто • заказы по месяцам"]); з.append(["Заказы всего", None, "Операций"]); з.append([1, None, 1])
    з.append(ШАПКА_З)
    р = wb.create_sheet("Расходы")
    р.append(["Крипто • расходы по месяцам"]); р.append(["Расходы всего", None, "Операций"]); р.append([1, None, 1])
    р.append(ШАПКА_Р)
    листы = {}
    for op in операции:
        op = list(op)
        if описания and op[0] in описания:
            op[8] = описания[op[0]]
        когда = datetime.strptime(op[1], "%d.%m.%Y %H:%M")
        m = когда.strftime("%Y-%m")
        if m not in листы:
            ws = wb.create_sheet(f"Месяц {m}")
            ws.append([f"Крипто операции • {m}"]); ws.append(["Заказы AED", None, "Кол-во заказов", None, "Выдача AED"])
            ws.append([1, None, 1, None, 1]); ws.append(["Пополнения", None, "Баланс на конец"])
            # ломаная шапка: значения в первых ячейках, названия — с шестой
            ws.append([0, None, 44, None, None, "Курс AED", "Приход/расход AED", "Баланс после", "Описание"])
            ws.append(["Смена #1", None, None, None, None, None, 0])
            листы[m] = ws
        листы[m].append(op)
        if op[2] == "Приход от клиента":
            з.append([op[0], op[1], op[2], op[3], op[4], op[5], op[6], "", op[8]])
        else:
            р.append([op[0], op[1], op[2], op[3], op[4], op[5], op[6], op[7], op[8]])
    buf = io.BytesIO(); wb.save(buf)
    return buf.getvalue()
