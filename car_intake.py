"""Приём машины: пробег на въезде.

Владелец, 29 сен 2026: «водители, которые приезжают новенькие или с отпуска,
должны будут фотографировать пробег машины и вписывать его вручную, это будет
процедурой принятия автомобиля; без этого выйти на работу будет нельзя».

Когда требуем
-------------
Не «новенький» флажком, а **новый период работы**. Периоды и так живут в
«Зарплатах» и уже отвечают на вопрос, кто уехал ([[project_away_drivers]]);
второй реестр рядом с первым рано или поздно с ним разойдётся. Поэтому ключ
приёма — имя плюс день начала текущего периода:

  • пришёл новенький   → первый период  → требуем;
  • вернулся из отпуска → новый период   → требуем снова;
  • работает без перерыва → период тот же → спросили один раз, и хватит.

Рубеж
-----
Владелец, 29 сен 2026: «к Муину и Фахридину не нужно сейчас это применять, это
начнём со следующих приехавших водителей». Значит требуем только у тех, чей
период НАЧАЛСЯ не раньше FROM_DAY. Все, кто уже в работе, проходят мимо — их
период старше рубежа. Так же сделан перенос выручки (CASH_CARRY_FROM): у правил,
которые включают посреди жизни, должна быть дата включения, иначе первым делом
они бьют по тем, кого не имели в виду.

Чего здесь НЕТ
--------------
Сдачи машины при отъезде. Владелец выбрал «только приём, как просили» (29 сен
2026). Без пары разница между двумя приёмами — это километры всех, кто ездил на
машине, а не одного человека; знать это про цифру стоит.

С 1 октября 2026 — каждый месяц и при каждой смене машины
---------------------------------------------------------
Владелец, 30 сен 2026: «каждое первое число перед открытием смены водитель
точно так же должен фоткать пробег машины и вписывать вручную эту цифру, без
этого смену открыть будет нельзя… каждый месяц и каждую смену водителями авто,
если например они поменялись машинами или приехал новый водитель вместо
уехавшего».

Показание нужно, если у ЭТОГО водителя по ЭТОЙ машине нет показания позже
последнего из трёх событий:

  new    — вышел на работу (правило выше, с его рубежом FROM_DAY);
  car    — машину закрепили за ним (cars.at): поменялись — снимают оба, вернули
           назад — снимают снова, между показаниями ездил другой;
  month  — начался месяц: первая смена с 1-го числа. Кто 1-го выходной —
           в свой первый рабочий день.

Сутки — учётные (bizday): ночь на 1-е ещё «вчера», открытую смену правило не
прерывает. Запись больше не одна на период, а журнал: у каждого показания свой
_id, причина (why) и учётный день (day). Рубеж месячного правила —
MONTHLY_FROM: до него работает только «вышел на работу».

Машины нет и свободных нет — снимать нечего, на смену пускаем; в STAR такой
водитель виден строкой «без машины».
"""
import os

import bizday
import config_staff as staff
import db

# День, с которого действует «вышел на работу». Период, начавшийся раньше,
# сам по себе ничего не требует.
FROM_DAY = os.getenv("AMBAR_CAR_INTAKE_FROM", "2026-09-29")
# День, с которого показание нужно каждый месяц и при смене машины — всем.
MONTHLY_FROM = os.getenv("AMBAR_CAR_MONTHLY_FROM", "2026-10-01")

# Пределы здравого смысла для числа, вписанного руками. Не «проверка», а сито
# от лишнего нуля и от пустого поля.
KM_MIN, KM_MAX = 1, 2_000_000
# Насколько пробег может прыгнуть с прошлого показания, чтобы не переспрашивать.
# Машина по городу ходит 100–200 км в день; 50 000 — это месяцы работы.
KM_JUMP = 50_000

WHY_RU = {"new": "вышел на работу", "car": "сел на машину", "month": "начало месяца",
          "repair": "сдал в ремонт", "repair_back": "забрал из ремонта"}


def _int(v) -> int:
    try:
        return int(str(v).strip().replace(" ", "").replace("\u00a0", ""))
    except (TypeError, ValueError):
        return 0


def today() -> str:
    return bizday.biz_day()


def rec_day(rec: dict | None) -> str:
    """Учётный день показания (у записей 29–30 сен поля day ещё не было)."""
    if not rec:
        return ""
    return str(rec.get("day") or "") or (bizday.day_of(rec.get("at")) or "")


def why_need(since: str, car: dict | None, mine: dict | None, day: str,
             any_mine: dict | None = None) -> str:
    """Почему нужно показание: 'new' | 'car' | 'month' | '' (не нужно).

    mine — последнее показание этого водителя по этой машине (или пропуск
    владельца: он закрывает требование так же, как показание); any_mine —
    его последнее показание по любой машине: «вышел на работу» закрывается
    один раз за период, а пересел потом — это уже 'car'."""
    был = rec_day(mine)
    любое = any_mine if any_mine is not None else mine
    if since and since >= FROM_DAY and (not любое or rec_day(любое) < since):
        return "new"
    if day < MONTHLY_FROM:
        return ""
    взял = bizday.parse_ts((car or {}).get("at"))
    снял = bizday.parse_ts((mine or {}).get("at"))
    if взял and bizday.biz_day(взял) >= MONTHLY_FROM and (not снял or снял < взял):
        return "car"
    if not mine or был < day[:7] + "-01":
        return "month"
    return ""


async def state(me: dict) -> dict:
    """Что с показанием у этого водителя.

    need   — выйти на смену нельзя, пока не снял;
    why    — почему: new / car / month;
    since  — день начала периода работы (для подписи);
    car    — машина, которую снимает (или None — своей нет);
    free   — свободные машины, если своей нет: показание её же и закрепляет;
    nocar  — своей нет и свободных нет: снимать нечего, пускаем;
    last   — прошлое показание этой машины (чьё угодно): число рядом с новым
             видно сразу, и нелепая разница бросается в глаза без техники;
    done   — последнее своё показание по этой машине, если оно ещё в силе.
    """
    имя = str((me or {}).get("name") or "")
    пусто = {"need": False, "why": "", "since": "", "done": None, "car": None,
             "free": [], "last": None, "nocar": False, "repair": None}
    if not имя or (me or {}).get("test"):
        return пусто                                   # тест-водитель живёт вне «Зарплат»
    день = today()
    since = staff.work_since(имя)
    if день < MONTHLY_FROM and (not since or since < FROM_DAY):
        return пусто                                   # до 1 октября — только новые периоды
    машины = await db.cars_all()
    своя = next((c for c in машины if (c.get("driver") or "") == имя), None)
    out = dict(пусто, since=since or "")
    if not своя:
        # Показание по «никакой» машине снять нельзя. Есть свободные — выбирает
        # и снимает; нет — держать человека нечем.
        любое = await db.car_reading_mine(имя, "")
        why = why_need(since, None, любое, день)
        free = [c for c in машины if not (c.get("driver") or "")]
        out.update(need=bool(why and free), why=why if free else "", free=free if why else [],
                   nocar=not free)
        return out
    cid = str(своя.get("_id") or "")
    моё = await db.car_reading_mine(имя, cid)
    # Машина в ремонте (владелец, 1 окт 2026: «перед сдачей водитель так же
    # фоткает одометр»): её у водителя нет, снимать нечего — на смену пускаем.
    # Пробег он снял при сдаче и снимет, когда заберёт.
    if своя.get("repair"):
        out.update(car=своя, done=моё, repair=своя.get("repair"))
        return out
    why = why_need(since, своя, моё, день, await db.car_reading_mine(имя, ""))
    out.update(need=bool(why), why=why, car=своя, done=None if why else моё)
    if why:
        out["last"] = await db.car_intake_last(cid)
    return out


def check_km(km, last: dict | None) -> tuple[int, str]:
    """(число, код ошибки). Пустой код — принято.

    less  — меньше, чем было в прошлый приём: одометр назад не ходит, и это
            почти всегда опечатка или чужая машина;
    jump  — прыжок больше KM_JUMP: не запрет, а повод переспросить, поэтому
            приложение шлёт confirm=1 и число проходит.
    """
    n = _int(km)
    if n < KM_MIN or n > KM_MAX:
        return n, "bad_km"
    было = _int((last or {}).get("km"))
    if было and n < было:
        return n, "less"
    if было and n - было > KM_JUMP:
        return n, "jump"
    return n, ""
