"""Приём машины: пробег на въезде.

Владелец, 29 сен 2026: «водители, которые приезжают новенькие или с отпуска,
должны будут фотографировать пробег машины и вписывать его вручную, это будет
процедурой принятия автомобиля; без этого выйти на работу будет нельзя».

Когда требуем
-------------
Не «новенький» флажком, а **новый период работы**. Периоды и так живут в
«Зарплатах» и уже отвечают на вопрос, кто уехал ([[project_away_drivers]]);
второй реестр рядом с первым рано или поздно с ним разойдётся. Поэтому ключ
приёма — имя плюс день начала текущего периода:

  • пришёл новенький   → первый период  → требуем;
  • вернулся из отпуска → новый период   → требуем снова;
  • работает без перерыва → период тот же → спросили один раз, и хватит.

Рубеж
-----
Владелец, 29 сен 2026: «к Муину и Фахридину не нужно сейчас это применять, это
начнём со следующих приехавших водителей». Значит требуем только у тех, чей
период НАЧАЛСЯ не раньше FROM_DAY. Все, кто уже в работе, проходят мимо — их
период старше рубежа. Так же сделан перенос выручки (CASH_CARRY_FROM): у правил,
которые включают посреди жизни, должна быть дата включения, иначе первым делом
они бьют по тем, кого не имели в виду.

Чего здесь НЕТ
--------------
Сдачи машины при отъезде. Владелец выбрал «только приём, как просили» (29 сен
2026). Без пары разница между двумя приёмами — это километры всех, кто ездил на
машине, а не одного человека; знать это про цифру стоит.
"""
import os

import config_staff as staff
import db

# День, с которого правило действует. Период, начавшийся раньше, ничего не
# требует.
FROM_DAY = os.getenv("AMBAR_CAR_INTAKE_FROM", "2026-09-29")

# Пределы здравого смысла для числа, вписанного руками. Не «проверка», а сито
# от лишнего нуля и от пустого поля.
KM_MIN, KM_MAX = 1, 2_000_000
# Насколько пробег может прыгнуть с прошлого приёма, чтобы не переспрашивать.
# Машина по городу ходит 100–200 км в день; 50 000 — это месяцы работы.
KM_JUMP = 50_000


def _int(v) -> int:
    try:
        return int(str(v).strip().replace(" ", "").replace(" ", ""))
    except (TypeError, ValueError):
        return 0


async def state(me: dict) -> dict:
    """Что с приёмом у этого водителя.

    need   — выйти на смену нельзя, пока не принял;
    since  — период, за который принимаем (он же ключ записи);
    car    — машина, которую принимает (или None — своей нет);
    free   — свободные машины, если своей нет: принять можно только машину,
             и приём — то место, где её и выдают;
    last   — прошлый приём этой машины: число рядом с новым видно сразу, и
             нелепая разница бросается в глаза без всякой техники.
    """
    имя = str((me or {}).get("name") or "")
    пусто = {"need": False, "since": "", "done": None, "car": None, "free": [], "last": None}
    if not имя or (me or {}).get("test"):
        return пусто                                   # тест-водитель живёт вне «Зарплат»
    since = staff.work_since(имя)
    if not since or since < FROM_DAY:
        # Периодов нет вовсе или человек вышел до включения правила.
        return пусто
    rec = await db.car_intake_get(имя, since)
    машины = await db.cars_all()
    своя = next((c for c in машины if (c.get("driver") or "") == имя), None)
    out = {"need": not rec, "since": since, "done": rec, "car": своя, "free": [], "last": None}
    if rec:
        return out
    if not своя:
        out["free"] = [c for c in машины if not (c.get("driver") or "")]
    else:
        out["last"] = await db.car_intake_last(str(своя.get("_id") or ""))
    return out


def check_km(km, last: dict | None) -> tuple[int, str]:
    """(число, код ошибки). Пустой код — принято.

    less  — меньше, чем было в прошлый приём: одометр назад не ходит, и это
            почти всегда опечатка или чужая машина;
    jump  — прыжок больше KM_JUMP: не запрет, а повод переспросить, поэтому
            приложение шлёт confirm=1 и число проходит.
    """
    n = _int(km)
    if n < KM_MIN or n > KM_MAX:
        return n, "bad_km"
    было = _int((last or {}).get("km"))
    if было and n < было:
        return n, "less"
    if было and n - было > KM_JUMP:
        return n, "jump"
    return n, ""
