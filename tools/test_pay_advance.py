"""Авансы и своя премия (владелец, 19 сен 2026: «водители могут попросить
зарплату наперёд авансом — надо понимать, получил он зарплату наперёд или
часть авансом; он должен видеть, сколько получает в этом месяце с учётом
премии и сколько в следующем с учётом того, что часть или всю зарплату уже
выплатили; премии настраиваемые каждому свои»). Чистая математика
finance_pay и тексты сообщения водителю, без базы.
  • своя премия в месяц — как оклад: с месяца, где вписана, и дальше; 0 —
    с этого месяца премии нет;
  • аванс «часть зарплаты» снимается с этого месяца, «зарплата наперёд» — с
    следующего целиком, «по частям» — по графику;
  • разбивка: премия в месяц, разовые, штрафы, удержания, аванс, долг."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.setdefault("MONGO_URI", "")
import logging
logging.disable(logging.CRITICAL)
import finance_pay as pay
import pay_notify as pn

FAIL = []
def eq(name, got, want):
    ok = got == want
    print(("  ok  " if ok else "  FAIL") + f" {name}: {got!r}" + ("" if ok else f" ≠ {want!r}"))
    if not ok: FAIL.append(name)

P = {"name": "Худоба", "role": "driver"}
DOCS = [{"month": "2026-08", "name": "Худоба", "rate": 3000, "unit": "month", "cur": "AED", "bonus": 300},
        {"month": "2026-11", "name": "Худоба", "bonus": 0}]
def row(month, items, payouts=()):
    docs = [d for d in DOCS if d["month"] <= month]
    eff = pay.effective({**P, "_month": month}, docs)
    return pay.person_month(P, month, eff, 0, items, list(payouts), 3.67)

print("── своя премия в месяц ────────────────────────────────────────")
r = row("2026-09", [])
eq("сентябрь: оклад 3000 + премия 300 (вписана в августе)", (r["accrued"], r["bonus_month"], r["plus"], r["to_pay"]),
   (3000, 300, 300, 3300))
eq("премия задана", r["bonus_set"], True)
r = row("2026-11", [])
eq("ноябрь: премию обнулили — 0, к выплате 3000", (r["bonus_month"], r["to_pay"]), (0, 3000))

print("── аванс частью: в счёт этого месяца ──────────────────────────")
part = {"_id": "a1", "name": "Худоба", "kind": "advance", "mode": "part", "amount": 1000, "per_month": 0,
        "from": "2026-09", "day": "2026-09-12"}
r = row("2026-09", [part])
eq("сентябрь: 3000 + 300 − аванс 1000 = 2300", (r["advance"], r["minus"], r["to_pay"]), (1000, 1000, 2300))
eq("строка аванса — со смыслом", (r["items"][0]["t"], r["items"][0]["mode"]), ("Аванс — часть зарплаты", "part"))
r = row("2026-10", [part])
eq("октябрь: аванс уже снят — полные 3300", (r["advance"], r["to_pay"]), (0, 3300))

print("── вся зарплата наперёд: в сентябре — октябрьская ─────────────")
ahead = {"_id": "a2", "name": "Худоба", "kind": "advance", "mode": "ahead", "amount": 3300, "per_month": 0,
         "from": "2026-10", "day": "2026-09-19"}
r = row("2026-09", [ahead])
eq("сентябрь: не тронут — 3300", (r["advance"], r["to_pay"]), (0, 3300))
r = row("2026-10", [ahead])
eq("октябрь: 3000 + 300 − 3300 наперёд = 0", (r["advance"], r["to_pay"]), (3300, 0))
eq("строка: «Зарплата наперёд»", r["items"][0]["t"], "Зарплата наперёд")

print("── по частям, со штрафом и разовой премией рядом ──────────────")
custom = {"_id": "a3", "name": "Худоба", "kind": "advance", "mode": "custom", "amount": 1500, "per_month": 500,
          "from": "2026-09", "day": "2026-09-05"}
fine = {"_id": "f1", "name": "Худоба", "kind": "fine", "amount": 100, "per_month": 0, "from": "2026-09", "day": "2026-09-10"}
once = {"_id": "b1", "name": "Худоба", "kind": "bonus", "amount": 200, "per_month": 0, "from": "2026-09", "day": "2026-09-15"}
r = row("2026-09", [custom, fine, once], [{"amount": 1000}])
eq("сентябрь: 3000 + 300 + 200 − аванс 500 − штраф 100 = 2900",
   (r["plus"], r["bonus_once"], r["advance"], r["fines"], r["minus_other"], r["to_pay"]), (500, 200, 500, 100, 100, 2900))
eq("выплачено 1000 — осталось 1900", (r["paid"], r["left"]), (1000, 1900))
eq("долг по авансу после сентября — 1000", r["debt"], 1000)
r = row("2026-11", [custom])
eq("ноябрь: последний кусок 500, премии уже нет → 2500", (r["advance"], r["to_pay"]), (500, 2500))
r = row("2026-12", [custom])
eq("декабрь: аванс погашен", (r["advance"], r["to_pay"]), (0, 3000))

print("── сообщение водителю: что именно выдали ──────────────────────")
t = pn.added(ahead, "Старший")
eq("«Зарплата за октябрь 2026 наперёд — выдана 19 сентября»",
   ("Зарплата за октябрь 2026 наперёд" in t, "выдана 19 сентября" in t), (True, True))
t = pn.added(part, "Старший")
eq("«Аванс … в счёт зарплаты за сентябрь 2026 — выдан 12 сентября»",
   ("в счёт зарплаты за сентябрь 2026" in t, "выдан 12 сентября" in t), (True, True))
t = pn.added(custom, "Старший")
eq("по частям — с графиком удержания", "по 500 AED в месяц" in t, True)

print("ИТОГ:", "все прошли" if not FAIL else f"провалено {len(FAIL)}: {FAIL}")
sys.exit(1 if FAIL else 0)
