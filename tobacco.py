"""Табак: что это такое и почему его нельзя заказать одному.

Сигареты мы продаём только в паре с алкоголем. Причина не в выкладке и не в
маркетинге: доставка едет ради заказа, а пачка за двадцать пять дирхам не
окупает ни машину, ни водителя, ни время оператора. Табак здесь — то, что
докладывают к бутылке, а не то, за чем едут.

Правило живёт в одном месте, потому что проверяется в трёх: приложение не даёт
оформить, сервер не принимает, оператор видит причину теми же словами. Три
копии условия разойдутся молча — и разойдутся именно в тот день, когда кто-то
добавит новую категорию.

Здесь же граница «что считается алкоголем». Сегодня алкоголь — это весь
каталог, кроме табака, и написано это явно: когда появятся снеки или лёд, их
надо будет дописать в NON_ALCOHOL, а не гадать, почему пачка чипсов вдруг
разблокировала заказ сигарет.
"""

CAT = "Сигареты"
CAT_EN = "Cigarettes"

# Категории, которые сами по себе заказ не составляют.
NON_ALCOHOL = {CAT}

# Что видит человек, когда правило сработало. Один текст на бота, оператора и
# ответ сервера: клиент не должен получать в трёх местах три разные формулировки.
WHY_RU = "Сигареты доставляем только вместе с алкоголем"
WHY_EN = "Cigarettes are delivered only together with alcohol"


def is_tobacco(p: dict) -> bool:
    return bool(p) and (p.get("cat") or "") in NON_ALCOHOL


def is_alcohol(p: dict) -> bool:
    return bool(p) and (p.get("cat") or "") not in NON_ALCOHOL


def split(items: list, catalog: dict) -> tuple:
    """(сколько табака, сколько алкоголя) в заказе.

    Позиции, которых нет в каталоге, считаем алкоголем: неизвестное — не повод
    отказать человеку в заказе, а повод разобраться с каталогом. Подарок в счёт
    не идёт вовсе: его кладёт сервер, и разблокировать им табак нельзя."""
    smokes = booze = 0
    for it in (items or []):
        if it.get("gift"):
            continue
        try:
            qty = int(it.get("qty") or 0)
        except (TypeError, ValueError):
            qty = 0
        if qty <= 0:
            continue
        p = catalog.get(it.get("id"))
        if p is not None and is_tobacco(p):
            smokes += qty
        else:
            booze += qty
    return smokes, booze


def order_blocked(items: list, catalog: dict) -> bool:
    """Заказ из одного табака — единственное, что запрещено."""
    smokes, booze = split(items, catalog)
    return bool(smokes) and not booze
