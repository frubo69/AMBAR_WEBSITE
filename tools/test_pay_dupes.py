"""Тёзки в зарплатной ведомости (владелец, 23 сен 2026: «где водитель Парвиз?
не старший оператор, а водитель»; «заканчивай с синхронизацией, чтобы у нас
везде были одинаковые сотрудники»).

У нас Парвиз — и старший оператор, и водитель на Бизнес Бей; Фарух — и
оператор, и водитель на JVC. Это разные люди (разные телеграм-аккаунты), а
человек в ведомости — это его имя: под именем лежат оклад, штрафы и авансы.
Раньше второй молча исчезал — в расписании 13 водителей, в ведомости 11.

Имя отдано ВОДИТЕЛЮ: по имени водителя ходит вся автоматика (смены, штрафы,
урезанное питание, чай, удержания за бой). Оператор-тёзка живёт под уточнённым
ключом «Парвиз · старший», а на экране он по-прежнему Парвиз.

Без базы: настоящий finance_routes._people, расписание — заглушка.

    python3 tools/test_pay_dupes.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.setdefault("MONGO_URI", "")
os.environ.setdefault("AMBAR_OWNER_IDS", "1")
import logging; logging.disable(logging.WARNING)
import config_staff as staff                                   # noqa: E402
import finance_routes as fr                                    # noqa: E402

FAIL = []
def eq(имя, дали, ждём):
    ок = дали == ждём
    print(("  ok  " if ок else "  FAIL") + f" {имя}: {дали!r}" + ("" if ок else f" ≠ {ждём!r}"))
    if not ок: FAIL.append(имя)

staff.SENIOR_OPERATORS = [{"name": "Парвиз"}]
staff.operators = lambda: [{"name": "Парвиз", "senior": True, "districts": ["bbay"]},
                           {"name": "Умар", "districts": ["tecom"]},
                           {"name": "Фарух", "districts": ["jvc"]}]
ВОДИТЕЛИ = [{"name": "Худоба", "district": "jvc"},
            {"name": "Фарух", "district": "jvc"},        # тёзка оператора
            {"name": "Парвиз", "district": "bbay"},      # тёзка старшего
            {"name": "Авазбек", "district": "bbay"}]
staff.drivers = lambda: list(ВОДИТЕЛИ)


def main():
    dupes: list = []
    люди = fr._people([], dupes)
    по_роли = {}
    for p in люди:
        по_роли.setdefault(p["role"], []).append((p["name"], p["title"]))

    eq("все водители на месте — столько же, сколько в расписании",
       [n for n, _ in по_роли.get("driver", [])], ["Худоба", "Фарух", "Парвиз", "Авазбек"])
    eq("у водителя — обычное имя: по нему ходят смены, штрафы и питание",
       [(n, t) for n, t in по_роли.get("driver", []) if n in ("Парвиз", "Фарух")],
       [("Фарух", "Фарух"), ("Парвиз", "Парвиз")])
    eq("старший-тёзка — под уточнённым ключом, а зовут его по-прежнему",
       по_роли.get("senior"), [("Парвиз · старший", "Парвиз")])
    eq("оператор-тёзка — так же", [x for x in по_роли.get("operator", []) if x[1] == "Фарух"],
       [("Фарух · оператор", "Фарух")])
    eq("оператор без тёзки имя не меняет",
       [x for x in по_роли.get("operator", []) if x[1] == "Умар"], [("Умар", "Умар")])
    eq("никто не пропал и жаловаться не на что", dupes, [])

    # Ключ не меняется, когда тёзка-водитель уволился: оклад и авансы лежат
    # под ним, и переименование оставило бы их в пустоте.
    staff.drivers = lambda: [{"name": "Худоба", "district": "jvc"}]
    люди2 = fr._people([{"_id": "Парвиз · старший", "role": "senior"}], [])
    eq("уволился тёзка — ключ уже заведённого остался прежним",
       [(p["name"], p["title"]) for p in люди2 if p["role"] == "senior"],
       [("Парвиз · старший", "Парвиз")])

    # Два водителя с одним именем — это по-прежнему неразрешимо, и об этом
    # надо говорить: имя у них общее, а деньги разные.
    staff.drivers = lambda: [{"name": "Худоба", "district": "jvc"},
                             {"name": "Худоба", "district": "bbay"}]
    d3: list = []
    fr._people([], d3)
    eq("два водителя-тёзки — по-прежнему красная строка",
       [(x["name"], x["kept"], x["lost"]) for x in d3], [("Худоба", "driver", "driver")])

    print("\nИТОГ:", "все прошли" if not FAIL else f"провалено {len(FAIL)}: {FAIL}")
    return 1 if FAIL else 0


sys.exit(main())
