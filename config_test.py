"""Тестовые аккаунты владельца — те, на которых проверяют приложение.

В чат их сообщения приходят как обычно: там они и нужны, иначе проверить
поддержку было бы нечем. А вот в архив и в выгрузку они попадать не должны —
документ с историей заявок, списаний и доступов теряет смысл, если половина
строк в нём про заказ, который никто не собирался везти.

Список отдельный от `_TEST_ACCOUNTS` в api_server: тот управляет ходом заказа
(верификация, первый заказ, оплата), и дописывать туда лишний id — значит
менять поведение боевого сценария ради фильтра в отчёте.
"""

import os

_ENV_IDS = {int(x) for x in os.getenv("AMBAR_ARCHIVE_SKIP_IDS", "").split(",")
            if x.strip().isdigit()}

# id владельческих тестовых аккаунтов
ARCHIVE_SKIP_IDS = {
    686932322,    # fixxxik · @trxxxman1a
    7236406959,   # x · @traxxxxman1a
    6731325660,   # kiss or slap💋 (без ника)
    8251195567,   # тестовый аккаунт из _TEST_ACCOUNTS
} | _ENV_IDS

# То, чем эти аккаунты подписаны в тексте уведомления: id есть не везде.
ARCHIVE_SKIP_MARKS = {
    "@trxxxman1a",
    "@traxxxxman1a",
    "kiss or slap",
}


def skip_patterns() -> list:
    """Строки, по которым уведомление опознаётся как тестовое."""
    return [str(i) for i in sorted(ARCHIVE_SKIP_IDS)] + sorted(ARCHIVE_SKIP_MARKS)
