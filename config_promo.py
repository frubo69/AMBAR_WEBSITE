def matches(text: str) -> bool:
    """Похоже ли, что человек ищет, где взять."""
    t = (text or "").lower()
    if not t or len(t) > MAX_LEN:
        return False
    if any(w in t for w in STRONG):
        return True
    return any(w in t for w in INTENT) and any(w in t for w in SUBJECT)
