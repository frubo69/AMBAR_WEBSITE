"""Сторож снаружи не кричит, когда связи нет У НЕГО (заплатка 29 сен 2026).

28 сентября сторож поднял пять ложных тревог: рвалась связь у мака, а он
доложил «сайт не отвечает». Сервер был цел — службу и nginx в тот день не
перезапускали ни разу.

  • сервер молчит, своей связи нет — ни слова, счётчик не растёт;
  • слепота копится, а не начинается заново на каждой проверке;
  • связь вернулась, сервер цел — сказать, сколько не смотрели;
  • слепота короче четверти часа — молча, это не новость;
  • сервер молчит, а своя связь есть — тревога как раньше, со второй неудачи;
  • одиночный чих по-прежнему не будит.

    python3 tools/test_outside_watch.py
"""
import os, sys, tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import outside_watch as W                                         # noqa: E402

FAIL = []
def eq(имя, дали, ждём):
    ок = дали == ждём
    print(("  ok  " if ок else "  FAIL") + f" {имя}: {дали!r}" + ("" if ок else f" ≠ {ждём!r}"))
    if not ок: FAIL.append(имя)

ПАПКА = tempfile.mkdtemp()
W.СОСТОЯНИЕ = os.path.join(ПАПКА, "state")
W.ЖУРНАЛ = os.path.join(ПАПКА, "log")
W.настройки = lambda: {"ip": "203.0.113.9", "host": "x.invalid",
                       "token": "t", "chat_ids": [1]}
ПИСЬМА = []
W.написать = lambda token, ids, текст: (ПИСЬМА.append(текст), True)[1]

ЧАСЫ = [1_700_000_000]
W.time.time = lambda: ЧАСЫ[0]


def прогон(ssh, http, своя, через=60):
    """Одна проверка сторожа с заданным миром."""
    ЧАСЫ[0] += через
    W.ssh_жив = lambda ip, секунд=6: ssh
    W.http_жив = lambda ip, host, секунд=8: (http, 200 if http else 0)
    W.сеть_своя = lambda секунд=4: своя
    return W.main()


print("── сервер молчит, а связи нет у нас ───────────────────────────────")
for i in range(20):                               # 20 минут вслепую
    прогон(ssh=True, http=False, своя=False)
eq("НИ ОДНОГО СООБЩЕНИЯ", ПИСЬМА, [])
eq("счётчик неудач не рос", W.прошлое().get("плохо", 0), 0)
eq("и сервер не числится лежащим", W.прошлое().get("лежит_с", 0), 0)
слеп = W.прошлое().get("слеп_с")
eq("слепота засечена один раз", слеп, 1_700_000_000 + 60)

print("── связь вернулась, сервер цел ────────────────────────────────────")
прогон(ssh=True, http=True, своя=True)
eq("сказал, сколько не смотрел", len(ПИСЬМА), 1)
eq("и назвал время", "20 мин" in (ПИСЬМА[0] if ПИСЬМА else ""), True)
eq("про сервер ничего не выдумал", "не отвечает" in (ПИСЬМА[0] if ПИСЬМА else ""), False)
eq("слепота сброшена", W.прошлое().get("слеп_с"), 0)

print("── слепота короче четверти часа — молча ───────────────────────────")
ПИСЬМА.clear()
прогон(ssh=True, http=False, своя=False)
прогон(ssh=True, http=True, своя=True)
eq("ни слова", ПИСЬМА, [])

print("── сервер молчит, а связь у нас есть — как раньше ─────────────────")
ПИСЬМА.clear()
прогон(ssh=True, http=False, своя=True)
eq("первый чих не будит", ПИСЬМА, [])
прогон(ssh=True, http=False, своя=True)
eq("со второй неудачи — тревога", len(ПИСЬМА), 1)
eq("и словами про сайт", "сайт не отвечает" in (ПИСЬМА[0] if ПИСЬМА else ""), True)

print("── посреди настоящего простоя у нас отвалился интернет ────────────")
ПИСЬМА.clear()
прогон(ssh=True, http=False, своя=False)          # ослепли
eq("молчим, пока слепые", ПИСЬМА, [])
eq("но сервер всё ещё числится лежащим", bool(W.прошлое().get("лежит_с")), True)
прогон(ssh=True, http=True, своя=True)
eq("поднялся — сказали про сервер", any("снова отвечает" in т for т in ПИСЬМА), True)

print("── сервер цел, связь есть — тишина ────────────────────────────────")
ПИСЬМА.clear()
прогон(ssh=True, http=True, своя=True)
eq("ни слова", ПИСЬМА, [])

print(("\nПРОВАЛЫ: " + ", ".join(FAIL)) if FAIL else "\nвсё сошлось")
sys.exit(1 if FAIL else 0)
