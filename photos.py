"""Снимки: чек расхода и кадр списания.

Один модуль на все фотографии, потому что главный предел здесь не наш. Тело
запроса режет aiohttp, и делает это раньше, чем обработчик успевает сказать
«тяжело». Пока пределы лежали в двух файлах порознь и оба стояли выше
транспортного потолка, человек вместо понятной подсказки получал 413 и пустой
экран: приложение ждало наш json, а приходила чужая ошибка.

Отсюда правило: MAX_PHOTO должен быть заметно ниже MAX_BODY в api_server, иначе
проверка ниже никогда не сработает.
"""

# Сколько base64 приходит в теле. Кадр 1280px при качестве 0.72 — это 270–550 КБ
# строкой; подробный чек на текстуре доходит до мегабайта. Берём с запасом.
MAX_PHOTO = 2_000_000
# Миниатюра 96px. Она едет не по запросу, а в каждой строке списка, поэтому
# предел у неё свой и жёсткий.
MAX_THUMB = 40_000
# Меньше двух килобайт — это не фотография, а сбой камеры или пустой кадр.
MIN_PHOTO = 2_000


def decode(raw: str) -> tuple[bytes, str]:
    """base64 (с префиксом data:image или без) → байты.

    Второе значение — код ошибки для ответа; пустая строка значит «в порядке».
    Пустой вход — не ошибка: снимок нужен не везде, и решает это вызывающий.
    """
    raw = str(raw or "")
    if "," in raw[:64]:
        raw = raw.split(",", 1)[1]
    if not raw:
        return b"", ""
    if len(raw) > MAX_PHOTO:
        return b"", "photo_big"
    try:
        import base64
        img = base64.b64decode(raw, validate=True)
    except Exception:                                        # noqa: BLE001
        return b"", "bad_photo"
    # Проверяем начало файла, а не длину строки: битая картинка ничего не
    # доказывает, а в истории выглядит так же, как настоящая.
    if len(img) < MIN_PHOTO or img[:2] not in (b"\xff\xd8", b"\x89P"):
        return b"", "bad_photo"
    return img, ""


def thumb(raw: str) -> str:
    """Миниатюра остаётся строкой: она рисуется вместе со строкой расхода, без
    второго запроса. Не картинка или слишком тяжёлая — молча пусто, ради
    миниатюры отказывать в записи незачем."""
    t = str(raw or "")
    return t if t.startswith("data:image/") and len(t) <= MAX_THUMB else ""
