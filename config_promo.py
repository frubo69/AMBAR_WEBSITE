def slug(q: str) -> str:
    """Метка площадки из того, что набрали после имени бота.

    Без неё все посты слились бы в один канал, и вопрос «какой чат окупается»
    остался бы без ответа. Пусто — общий пост."""
    q = "".join(c for c in (q or "").strip().lower()
                if c.isalnum() or c in "-_ ").strip().replace(" ", "-")
    return q[:24] or "all"


def matches(text: str) -> bool:
    """Похоже ли, что человек ищет, где взять."""
    t = (text or "").lower()
    if not t or len(t) > MAX_LEN:
        return False
    if any(w in t for w in STRONG):
        return True
    return any(w in t for w in INTENT) and any(w in t for w in SUBJECT)
